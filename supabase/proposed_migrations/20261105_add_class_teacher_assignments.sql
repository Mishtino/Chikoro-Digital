-- STAGING ONLY: teacher-to-class assignment foundation.
-- Existing student.form values are the source of class names until a
-- normalized class catalogue is introduced.

BEGIN;

DO $class_assignment$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_users_school_id_id' AND conrelid = 'public.users'::regclass) THEN
        ALTER TABLE public.users ADD CONSTRAINT uq_users_school_id_id UNIQUE (school_id, id);
    END IF;
END $class_assignment$;

CREATE TABLE IF NOT EXISTS public.class_teacher_assignments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id integer NOT NULL REFERENCES public.schools(id),
    class_name varchar(40) NOT NULL,
    teacher_user_id integer NOT NULL,
    assigned_by_user_id integer NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_class_teacher_assignment UNIQUE (school_id, class_name, teacher_user_id),
    CONSTRAINT fk_class_assignment_school_teacher
        FOREIGN KEY (school_id, teacher_user_id) REFERENCES public.users(school_id, id),
    CONSTRAINT fk_class_assignment_school_actor
        FOREIGN KEY (school_id, assigned_by_user_id) REFERENCES public.users(school_id, id),
    CONSTRAINT ck_class_assignment_name_nonempty CHECK (length(trim(class_name)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_class_assignments_school_teacher_active
    ON public.class_teacher_assignments (school_id, teacher_user_id, is_active);

ALTER TABLE public.class_teacher_assignments ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.class_teacher_assignments FROM anon, authenticated;

-- No browser-facing policies are added. The API remains responsible for
-- authorization; browser roles remain denied by default.

COMMIT;
