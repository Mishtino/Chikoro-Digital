-- attendance workflows have been validated and release approval is granted.

BEGIN;

-- Composite unique keys are required so child records cannot cross school
-- boundaries even when an API caller accidentally supplies mixed identifiers.
DO $
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_students_school_id_id' AND conrelid = 'public.students'::regclass) THEN
        ALTER TABLE public.students ADD CONSTRAINT uq_students_school_id_id UNIQUE (school_id, id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_terms_school_id_id' AND conrelid = 'public.terms'::regclass) THEN
        ALTER TABLE public.terms ADD CONSTRAINT uq_terms_school_id_id UNIQUE (school_id, id);
    END IF;
END $;

CREATE TABLE IF NOT EXISTS public.attendance_sessions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id integer NOT NULL REFERENCES public.schools(id),
    term_id integer NULL,
    class_name varchar(40) NOT NULL,
    attendance_date date NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'draft',
    recorded_by_user_id integer NOT NULL REFERENCES public.users(id),
    submitted_at timestamptz NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_attendance_session_school_class_date
        UNIQUE (school_id, class_name, attendance_date),
    CONSTRAINT uq_attendance_sessions_school_id_id UNIQUE (school_id, id),
    CONSTRAINT fk_attendance_sessions_school_term FOREIGN KEY (school_id, term_id) REFERENCES public.terms(school_id, id),
    CONSTRAINT ck_attendance_session_status
        CHECK (status IN ('draft', 'submitted')),
    CONSTRAINT ck_attendance_class_name_nonempty
        CHECK (length(trim(class_name)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_attendance_sessions_school_date
    ON public.attendance_sessions (school_id, attendance_date);
CREATE INDEX IF NOT EXISTS ix_attendance_sessions_term_id
    ON public.attendance_sessions (term_id);

CREATE TABLE IF NOT EXISTS public.attendance_records (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id integer NOT NULL REFERENCES public.schools(id),
    session_id integer NOT NULL,
    student_id integer NOT NULL,
    status varchar(20) NOT NULL,
    note text NULL,
    marked_by_user_id integer NOT NULL REFERENCES public.users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_attendance_record_session_student
        UNIQUE (session_id, student_id),
    CONSTRAINT fk_attendance_records_school_session
        FOREIGN KEY (school_id, session_id) REFERENCES public.attendance_sessions(school_id, id),
    CONSTRAINT fk_attendance_records_school_student
        FOREIGN KEY (school_id, student_id) REFERENCES public.students(school_id, id),
    CONSTRAINT ck_attendance_record_status
        CHECK (status IN ('present', 'absent', 'late', 'excused'))
);

CREATE INDEX IF NOT EXISTS ix_attendance_records_school_student
    ON public.attendance_records (school_id, student_id);
CREATE INDEX IF NOT EXISTS ix_attendance_records_session_id
    ON public.attendance_records (session_id);

ALTER TABLE public.attendance_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendance_records ENABLE ROW LEVEL SECURITY;

-- No browser-facing policies are added. Browser roles remain denied by
-- default; the API's database role and tenant checks remain the current
-- access boundary pending the dedicated least-privilege/RLS migration.

COMMIT;
