DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.users'::regclass
      AND conname = 'uq_users_school_id_id'
  ) THEN
    ALTER TABLE public.users
      ADD CONSTRAINT uq_users_school_id_id UNIQUE (school_id, id);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.students'::regclass
      AND conname = 'uq_students_school_id_id'
  ) THEN
    ALTER TABLE public.students
      ADD CONSTRAINT uq_students_school_id_id UNIQUE (school_id, id);
  END IF;
END $;

CREATE TABLE IF NOT EXISTS public.parent_teacher_conversations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id integer NOT NULL REFERENCES public.schools(id) ON DELETE CASCADE,
  student_id integer NOT NULL,
  parent_user_id integer NOT NULL,
  teacher_user_id integer NOT NULL,
  subject varchar(160) NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'open',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_parent_teacher_conversations_school_id UNIQUE (school_id, id),
  CONSTRAINT uq_parent_teacher_conversation_participants_subject
    UNIQUE (school_id, student_id, parent_user_id, teacher_user_id, subject),
  CONSTRAINT fk_parent_teacher_conversation_school_student
    FOREIGN KEY (school_id, student_id)
    REFERENCES public.students(school_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_parent_teacher_conversation_school_parent
    FOREIGN KEY (school_id, parent_user_id)
    REFERENCES public.users(school_id, id) ON DELETE RESTRICT,
  CONSTRAINT fk_parent_teacher_conversation_school_teacher
    FOREIGN KEY (school_id, teacher_user_id)
    REFERENCES public.users(school_id, id) ON DELETE RESTRICT,
  CONSTRAINT ck_parent_teacher_conversation_status
    CHECK (status IN ('open', 'closed')),
  CONSTRAINT ck_parent_teacher_conversation_subject
    CHECK (length(trim(subject)) > 0)
);

CREATE TABLE IF NOT EXISTS public.parent_teacher_messages (
  id bigserial PRIMARY KEY,
  school_id integer NOT NULL REFERENCES public.schools(id) ON DELETE CASCADE,
  conversation_id integer NOT NULL,
  sender_user_id integer NOT NULL,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_parent_teacher_messages_school_id UNIQUE (school_id, id),
  CONSTRAINT fk_parent_teacher_message_school_conversation
    FOREIGN KEY (school_id, conversation_id)
    REFERENCES public.parent_teacher_conversations(school_id, id) ON DELETE CASCADE,
  CONSTRAINT fk_parent_teacher_message_school_sender
    FOREIGN KEY (school_id, sender_user_id)
    REFERENCES public.users(school_id, id) ON DELETE RESTRICT,
  CONSTRAINT ck_parent_teacher_message_body CHECK (length(trim(body)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_parent_teacher_conversations_school_updated
  ON public.parent_teacher_conversations(school_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS ix_parent_teacher_conversations_parent
  ON public.parent_teacher_conversations(school_id, parent_user_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS ix_parent_teacher_conversations_teacher
  ON public.parent_teacher_conversations(school_id, teacher_user_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS ix_parent_teacher_messages_conversation_created
  ON public.parent_teacher_messages(school_id, conversation_id, created_at, id);

ALTER TABLE public.parent_teacher_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.parent_teacher_messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.parent_teacher_conversations FROM anon, authenticated;
REVOKE ALL PRIVILEGES ON TABLE public.parent_teacher_messages FROM anon, authenticated;
