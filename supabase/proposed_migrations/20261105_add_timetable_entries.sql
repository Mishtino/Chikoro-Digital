-- STAGING ONLY: school timetable foundation.
-- Apply only after reviewing the school-scoped composite foreign keys and
-- validating teacher/class/room conflict checks in staging.

BEGIN;

DO $timetable$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_users_school_id_id' AND conrelid = 'public.users'::regclass) THEN
        ALTER TABLE public.users ADD CONSTRAINT uq_users_school_id_id UNIQUE (school_id, id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_subjects_school_id_id' AND conrelid = 'public.subjects'::regclass) THEN
        ALTER TABLE public.subjects ADD CONSTRAINT uq_subjects_school_id_id UNIQUE (school_id, id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_terms_school_id_id' AND conrelid = 'public.terms'::regclass) THEN
        ALTER TABLE public.terms ADD CONSTRAINT uq_terms_school_id_id UNIQUE (school_id, id);
    END IF;
END $timetable$;

CREATE TABLE IF NOT EXISTS public.timetable_entries (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id integer NOT NULL REFERENCES public.schools(id),
    term_id integer NOT NULL,
    subject_id integer NOT NULL,
    teacher_user_id integer NULL,
    class_name varchar(40) NOT NULL,
    day_of_week integer NOT NULL,
    period_number integer NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    room varchar(80) NULL,
    created_by_user_id integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_timetable_class_day_period
        UNIQUE (school_id, term_id, class_name, day_of_week, period_number),
    CONSTRAINT fk_timetable_school_term
        FOREIGN KEY (school_id, term_id) REFERENCES public.terms(school_id, id),
    CONSTRAINT fk_timetable_school_subject
        FOREIGN KEY (school_id, subject_id) REFERENCES public.subjects(school_id, id),
    CONSTRAINT fk_timetable_school_teacher
        FOREIGN KEY (school_id, teacher_user_id) REFERENCES public.users(school_id, id),
    CONSTRAINT fk_timetable_school_creator
        FOREIGN KEY (school_id, created_by_user_id) REFERENCES public.users(school_id, id),
    CONSTRAINT ck_timetable_day_of_week CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_timetable_period_positive CHECK (period_number > 0),
    CONSTRAINT ck_timetable_time_range CHECK (start_time < end_time),
    CONSTRAINT ck_timetable_class_name_nonempty CHECK (length(trim(class_name)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_timetable_school_day_class
    ON public.timetable_entries (school_id, day_of_week, class_name);
CREATE INDEX IF NOT EXISTS ix_timetable_entries_teacher
    ON public.timetable_entries (school_id, teacher_user_id, day_of_week);

ALTER TABLE public.timetable_entries ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.timetable_entries FROM anon, authenticated;

-- No browser-facing policies are granted. API-side tenant authorization
-- remains mandatory; browser roles remain denied by default.

COMMIT;
