DO $homework$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'uq_subjects_school_id_id'
      AND conrelid = 'public.subjects'::regclass
  ) THEN
    ALTER TABLE public.subjects
      ADD CONSTRAINT uq_subjects_school_id_id UNIQUE (school_id, id);
  END IF;
END
$homework$;

CREATE TABLE public.homework_assignments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id integer NOT NULL REFERENCES public.schools(id),
  class_name varchar(40) NOT NULL CHECK (length(trim(class_name)) > 0),
  subject_id integer NOT NULL,
  term_id integer NULL,
  title varchar(160) NOT NULL CHECK (length(trim(title)) > 0),
  instructions text NOT NULL CHECK (length(trim(instructions)) > 0),
  due_at timestamptz NULL,
  status varchar(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','closed')),
  created_by_user_id integer NOT NULL,
  published_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_homework_assignments_school_id_id UNIQUE (school_id,id),
  CONSTRAINT fk_homework_school_subject FOREIGN KEY (school_id,subject_id) REFERENCES public.subjects(school_id,id),
  CONSTRAINT fk_homework_school_term FOREIGN KEY (school_id,term_id) REFERENCES public.terms(school_id,id),
  CONSTRAINT fk_homework_school_creator FOREIGN KEY (school_id,created_by_user_id) REFERENCES public.users(school_id,id)
);

CREATE TABLE public.homework_submissions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id integer NOT NULL REFERENCES public.schools(id),
  assignment_id integer NOT NULL,
  student_id integer NOT NULL,
  answer_text text NOT NULL CHECK (length(trim(answer_text)) > 0),
  status varchar(20) NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','marked')),
  submitted_at timestamptz NOT NULL DEFAULT now(),
  feedback text NULL,
  score numeric(7,2) NULL CHECK (score IS NULL OR score >= 0),
  marked_by_user_id integer NULL,
  marked_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_homework_submission_once UNIQUE (school_id,assignment_id,student_id),
  CONSTRAINT fk_homework_submission_school_assignment FOREIGN KEY (school_id,assignment_id) REFERENCES public.homework_assignments(school_id,id),
  CONSTRAINT fk_homework_submission_school_student FOREIGN KEY (school_id,student_id) REFERENCES public.students(school_id,id),
  CONSTRAINT fk_homework_submission_school_marker FOREIGN KEY (school_id,marked_by_user_id) REFERENCES public.users(school_id,id)
);

CREATE INDEX ix_homework_school_class_due ON public.homework_assignments(school_id,class_name,due_at);
CREATE INDEX ix_homework_submissions_school_student ON public.homework_submissions(school_id,student_id);

ALTER TABLE public.homework_assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.homework_submissions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.homework_assignments, public.homework_submissions FROM anon, authenticated;
