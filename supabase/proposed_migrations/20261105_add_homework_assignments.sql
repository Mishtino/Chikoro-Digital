  ADD CONSTRAINT uq_homework_submissions_school_id_id UNIQUE (school_id, id);

CREATE TABLE public.homework_attachments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id integer NOT NULL REFERENCES public.schools(id),
  submission_id integer NOT NULL,
  uploaded_by_user_id integer NOT NULL,
  object_path varchar(500) NOT NULL UNIQUE,
  original_filename varchar(255) NOT NULL,
  content_type varchar(120) NOT NULL,
  size_bytes integer NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 10485760),
  status varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','ready')),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_homework_attachments_school_id_id UNIQUE (school_id,id),
  CONSTRAINT fk_homework_attachment_school_submission
    FOREIGN KEY (school_id,submission_id)
    REFERENCES public.homework_submissions(school_id,id),
  CONSTRAINT fk_homework_attachment_school_uploader
    FOREIGN KEY (school_id,uploaded_by_user_id)
    REFERENCES public.users(school_id,id)
);

CREATE INDEX ix_homework_attachments_school_submission
  ON public.homework_attachments(school_id,submission_id);

ALTER TABLE public.homework_attachments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.homework_attachments FROM anon, authenticated;

